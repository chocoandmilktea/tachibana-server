//
// 【なぜ日付判定なのか】
// 以前は「最初のバッチが全件 stale なら休場」と判定していたが、staleは
// 「取得データの最終足の日付≠対象日」で立つため、
// ・8:50(0850)は当日の足がまだ1本も無く、平日でも必ず全件stale
// ・9:30もYahooの配信が数分遅れれば全件staleになりうる
// つまり営業日を休場と誤判定し、最重要である寄り付きのデータを丸ごと失う危険があった。
// 判定材料そのものが誤っていたため、日付で判定する方式に置き換えた。

