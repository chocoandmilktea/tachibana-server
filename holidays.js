// 上の一覧を検索用のSetに展開する（年を追記すれば自動で対象範囲が広がる）
var HOLIDAY_SET = (function () {
  var set = new Set();
  Object.keys(HOLIDAYS_BY_YEAR).forEach(function (year) {
    HOLIDAYS_BY_YEAR[year].forEach(function (day) { set.add(day); });
  });
  return set;
})();

// ── 日付の正規化 ───────────────────────────────────────────────────────
// 受け取った値を "YYYY-MM-DD"（JST）にそろえる。解釈できなければ null。
// Dateを渡された場合は「その瞬間を日本時間で見た日付」に変換する。
// Railwayのサーバー時刻はUTCのため、+9時間してからUTCの日付部分を取り出す
// （getFullYear() などのローカル時刻系を使うと9時間ずれる）。
function toDateString(date) {
  if (date instanceof Date) {
    if (isNaN(date.getTime())) return null;
    return new Date(date.getTime() + 9 * 60 * 60 * 1000).toISOString().slice(0, 10);
  }
  var text = String(date == null ? "" : date).trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(text) ? text : null;
}

// ── 本体 ───────────────────────────────────────────────────────────────
// 休場日なら true。dateはJSTのDate、または "YYYY-MM-DD" 文字列。
// 判定できない場合（日付が不正・対応年外）は false を返す。
// 誤って全スキャンを止めてしまうより、無駄に1回動くほうが安全なため。
function isMarketClosed(date) {
  var text = toDateString(date);
  var d = text ? new Date(text + "T00:00:00Z") : null;
  if (!d || isNaN(d.getTime())) {
    log("警告: 日付を解釈できません（営業日として扱います）:", date);
    return false;
  }

  // a. 土曜・日曜
  var dow = d.getUTCDay(); // 0=日曜 6=土曜
  if (dow === 0 || dow === 6) return true;

  // c. 年末年始休場（12/31・1/1〜1/3）。年をまたぐので祝日一覧より先に見る
  var monthDay = text.slice(5);
  if (monthDay === "12-31" || monthDay === "01-01" || monthDay === "01-02" || monthDay === "01-03") {
    return true;
  }

  // b. 国民の祝日・振替休日
  var year = text.slice(0, 4);
  if (!HOLIDAYS_BY_YEAR[year]) {
    log("警告: 祝日データが古いため " + year + "年 は判定できません（営業日として扱います）。" +
      "holidays.js の HOLIDAYS_BY_YEAR に " + year + "年分を追記してください");
    return false;
  }
  return HOLIDAY_SET.has(text);
}

module.exports = { isMarketClosed: isMarketClosed };
